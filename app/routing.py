"""app/routing.py

Маршрутизация адресата письма — куда по сути должно попасть обращение (Деканат,
Приёмная комиссия и т.д.). Это ОТДЕЛЬНОЕ решение от того, на какой физический
почтовый ящик уходит письмо (см. app/mailer.py и решение в README): реальной
интеграции с деканатами нет, поэтому фактически письмо всегда уходит на один
корпоративный ящик, а адресат — человекочитаемая метка в теме письма, по которой
сотрудник вручную пересылает или отвечает.

Это решение кода, а не модели: категорию уже извлекла LLM в analyze.py, а какому
адресату эта категория соответствует — фиксированная таблица без права модели её
менять. Так же, как приоритет и достаточность данных в app/rules.py.
"""
from __future__ import annotations

# Категории — те же, что в app/rules.py и CATEGORY_RU в app/api.py.
_CATEGORY_RECIPIENTS: dict[str, str] = {
    "admission": "Приёмная комиссия",
    "study": "Учебный отдел",
    "campus_life": "Студгородок",
    "account": "Техподдержка",
    "documents": "Учебный отдел",
    # "other" сознательно не перечислен — уходит в запасное значение ниже.
}

# Категория не опознана моделью или не входит в таблицу — письмо всё равно должно
# на что-то уйти, поэтому запасной адресат общий, а не отсутствие темы.
_FALLBACK_RECIPIENT = "Поддержка МИСИС"


def recipient(category: str, institute: str | None = None) -> str:
    """Человекочитаемое имя адресата по категории и (если известен) институту.

    Для категории "study" с известным институтом адресуем конкретному деканату —
    это точнее общего учебного отдела и не требует расширения таблицы под каждый
    институт заранее. "/" вырезаем: институт приходит от пользователя через
    known-поля черновика, а "/" — служебный разделитель темы письма (см. _subject
    в app/api.py), два подряд сломали бы разбор темы при повторной сборке.
    """
    institute = (institute or "").strip().replace("/", " ")
    if category == "study" and institute:
        return f"Деканат {institute}"
    return _CATEGORY_RECIPIENTS.get(category, _FALLBACK_RECIPIENT)
